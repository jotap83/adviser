export type TourProgress = { index: number; completed: boolean };
export function readTourProgress(
  raw: string | null,
): Record<string, TourProgress> {
  try {
    const parsed = JSON.parse(raw || "{}");
    if (!parsed || typeof parsed !== "object") return {};
    return Object.fromEntries(
      tours.flatMap((t) => {
        const p = parsed[t.id];
        return p &&
          Number.isInteger(p.index) &&
          p.index >= 0 &&
          p.index < t.steps.length
          ? [[t.id, { index: p.index, completed: p.completed === true }]]
          : [];
      }),
    );
  } catch {
    return {};
  }
}
